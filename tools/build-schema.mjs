// Packs db/*.sql into api/_schema.js so the Vercel Function carries the database setup with it.
// Run after editing any file in db/:  npm run build:schema
import fs from 'node:fs';
import path from 'node:path';
import { fileURLToPath } from 'node:url';

const ROOT = path.resolve(path.dirname(fileURLToPath(import.meta.url)), '..');
const files = fs.readdirSync(path.join(ROOT, 'db')).filter(f => f.endsWith('.sql')).sort();
// Version: the number given (npm run build:schema -- 3), otherwise the current one plus 1 when the SQL changed.
const prevFile = path.join(ROOT, 'api', '_schema.js');
const prev = fs.existsSync(prevFile) ? fs.readFileSync(prevFile, 'utf8') : '';
const prevVer = Number((prev.match(/SCHEMA_VERSION = (\d+)/) || [])[1] || 0);
const out = files.map(f => ({ name: f, sql: fs.readFileSync(path.join(ROOT, 'db', f), 'utf8') }));
const sqlJson = JSON.stringify(out, null, 1);
const VERSION = process.argv[2] ? Number(process.argv[2]) : (prev.includes(sqlJson) ? prevVer || 1 : prevVer + 1);
const body =
  '// GENERATED by tools/build-schema.mjs from the files in db/. Do not edit by hand.\n' +
  '// Bump SCHEMA_VERSION whenever the SQL changes so existing databases pick it up.\n' +
  'export const SCHEMA_VERSION = ' + VERSION + ';\n' +
  'export const SQL_FILES = ' + JSON.stringify(out, null, 1) + ';\n';
fs.writeFileSync(path.join(ROOT, 'api', '_schema.js'), body);
console.log('Wrote api/_schema.js with', files.join(', '));
